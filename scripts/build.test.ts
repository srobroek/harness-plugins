import { describe, expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { agentTexts, buildPlugin, composeAgents, mcpCopies, orphanAgents, readBuild } from "./build.ts"

const plugins = path.resolve(import.meta.dir, "../plugins")
const session = path.join(plugins, "session")
const statusline = path.join(plugins, "statusline")
const beads = path.join(plugins, "beads")

describe("buildPlugin", () => {
  test("inlines the shared lib and keeps host modules external", async () => {
    const outputs = await buildPlugin(session)
    const bundle = outputs.find((output) => output.file === path.join(session, "opencode/dist/index.js"))
    expect(bundle?.contents).toContain('from "@opencode/plugin"')
    expect(bundle?.contents).not.toContain("@srobroek/opencode-lib")
    expect(bundle?.contents).toContain("function parsedInvocations(")
  })

  test("writes a root shim for each entry", async () => {
    const outputs = await buildPlugin(session)
    const shim = outputs.find((output) => output.file === path.join(session, "opencode/index.js"))
    expect(shim?.contents).toContain('export { default } from "./dist/index.js"')
  })

  test("compiles TSX with the OpenTUI Solid transform and keeps the TUI runtime external", async () => {
    const outputs = await buildPlugin(statusline)
    const bundle = outputs.find((output) => output.file === path.join(statusline, "opencode/dist/tui.js"))
    expect(bundle?.contents).toContain('from "@opentui/solid"')
    expect(bundle?.contents).toContain("createElement")
    expect(bundle?.contents).toContain('from "solid-js"')
    expect(bundle?.contents).not.toContain("react")
    const shim = outputs.find((output) => output.file === path.join(statusline, "opencode/tui.js"))
    expect(shim?.contents).toContain('export { default } from "./dist/tui.js"')
  })

  test("bundles a Claude Code entry into claude/dist without a shim", async () => {
    const outputs = await buildPlugin(beads)
    expect(outputs.some((output) => output.file === path.join(beads, "claude/dist/claude-hook.js"))).toBe(true)
    expect(outputs.some((output) => output.file === path.join(beads, "opencode/dist/claude-hook.js"))).toBe(false)
    expect(outputs.some((output) => output.file === path.join(beads, "claude-hook.js") || output.file === path.join(beads, "opencode/claude-hook.js"))).toBe(false)
  })

  test("skips a directory without a package.json", async () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-empty-"))
    try {
      expect(await buildPlugin(dir)).toEqual([])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe("readBuild", () => {
  const manifest = (key: unknown) => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-manifest-"))
    writeFileSync(path.join(dir, "package.json"), JSON.stringify({ name: "x", "agent-plugins": key }))
    return dir
  }

  test("reads the harnesses, entries and Claude Code agent selection", () => {
    const dir = manifest({ harnesses: ["opencode", "claude"], entries: { index: "index" }, claudeEntries: { hook: "claude-hook" }, claudeAgents: ["a"] })
    try {
      expect(readBuild(dir)).toEqual({
        claude: true,
        harnesses: ["opencode", "claude"],
        entries: { index: "index" },
        claudeEntries: { hook: "claude-hook" },
        claudeAgents: ["a"],
      })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("an OpenCode-only plugin without entries builds nothing", () => {
    const dir = manifest({ harnesses: ["opencode"] })
    try {
      expect(readBuild(dir)).toEqual({ claude: false, harnesses: ["opencode"], entries: {}, claudeEntries: {} })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("rejects an entries map that does not name source files", () => {
    const dir = manifest({ harnesses: ["opencode"], entries: { index: 1 } })
    try {
      expect(() => readBuild(dir)).toThrow('"agent-plugins.entries" must map names to source file names')
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe("composeAgents", () => {
  const plugin = () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-agents-"))
    mkdirSync(path.join(dir, "agents.src"))
    mkdirSync(path.join(dir, "common", "agents"), { recursive: true })
    writeFileSync(path.join(dir, "agents.src", "rev.md"), "---\nmode: subagent\n---\nIntro.\n{{include core}}\n")
    return dir
  }
  const read = () => "<!-- part: a -->\nRule A."
  const composed = "---\n# Generated by scripts/build.ts from agents.src/rev.md. Do not edit.\nmode: subagent\n---\nIntro.\nRule A.\n"

  test("composes agents.src/<id>.md into common/agents/<id>.md with the generated comment", () => {
    const dir = plugin()
    try {
      expect(composeAgents(dir, false, read)).toEqual([{ file: path.join(dir, "common", "agents", "rev.md"), contents: composed }])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a plugin that also ships to Claude Code gets the OpenCode form, <id>.opencode.md", () => {
    const dir = plugin()
    try {
      expect(composeAgents(dir, true, read).map((output) => path.basename(output.file))).toEqual(["rev.opencode.md"])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a composed agent without a source is an orphan; a hand-written agent and a translation are not", () => {
    const dir = plugin()
    try {
      const outputs = composeAgents(dir, true, read)
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(agents, "gone.opencode.md"), "---\n# Generated by scripts/build.ts from agents.src/gone.md. Do not edit.\n---\nx")
      writeFileSync(path.join(agents, "own.opencode.md"), "---\nmode: subagent\n---\nx")
      writeFileSync(path.join(agents, "rev.claude.md"), "---\n# Generated by scripts/build.ts from common/agents/rev.opencode.md. Do not edit.\n---\nx")
      expect(orphanAgents(dir, outputs)).toEqual([path.join(agents, "gone.opencode.md")])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("agentTexts reads hand-written agents by id and lets a composed agent replace its file", () => {
    const dir = plugin()
    try {
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(agents, "own.opencode.md"), "own")
      writeFileSync(path.join(agents, "rev.opencode.md"), "stale")
      writeFileSync(path.join(agents, "own.claude.md"), "translated")
      const texts = agentTexts(dir, true, composeAgents(dir, true, read))
      expect(Object.fromEntries(texts)).toEqual({ own: "own", rev: composed })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("every shipped agents.src file composes to its committed common/agents file", () => {
    for (const name of ["agent-coder", "agent-reviewer", "delivery", "design", "quality", "speckit"]) {
      const dir = path.join(plugins, name)
      const build = readBuild(dir)
      for (const output of composeAgents(dir, build?.claude)) expect(readFileSync(output.file, "utf8")).toBe(output.contents)
    }
  })

  const shipped = (plugin: string, id: string) => {
    const dir = path.join(plugins, plugin, "common", "agents")
    return readFileSync(path.join(dir, readBuild(path.join(plugins, plugin))?.claude ? `${id}.opencode.md` : `${id}.md`), "utf8")
  }

  test("the composed coder prompt carries the quality line", () => {
    const prompt = shipped("agent-coder", "coder")
    expect(prompt).toContain("a summary of `quality-code-policy`, which you load before code; where they differ the skill wins")
    expect(prompt).toContain("only for new behavior")
  })

  test("the coder and the delivery implementers compose the coding-core method", () => {
    for (const [plugin, id] of [
      ["agent-coder", "coder"],
      ["delivery", "implementer"],
      ["delivery", "implementer-high"],
    ]) {
      const source = readFileSync(path.join(plugins, plugin as string, "agents.src", `${id}.md`), "utf8")
      expect({ id, includes: source.includes("{{include coding-core: method}}") }).toEqual({ id, includes: true })
    }
  })

  test("every code reviewer composes the test-change rules and the standards and testing parts", () => {
    for (const [plugin, id] of [
      ["agent-reviewer", "code-reviewer"],
      ["agent-reviewer", "pr-reviewer"],
      ["delivery", "pr-reviewer"],
    ]) {
      const prompt = shipped(plugin as string, id as string)
      expect({ id, rules: prompt.includes("MUST Map the test diff to the code diff") && prompt.includes("maintenance, not tampering") }).toEqual({ id, rules: true })
      expect({ id, standards: prompt.includes("- Standards first:") && prompt.includes("- Tests (`quality-testing`") }).toEqual({ id, standards: true })
    }
  })

  test("every code-writing agent composes the engineering and testing standards", () => {
    for (const [plugin, id] of [
      ["agent-coder", "coder"],
      ["delivery", "implementer"],
      ["delivery", "implementer-high"],
      ["design", "ui-implementer"],
    ]) {
      const prompt = shipped(plugin as string, id as string)
      expect({ id, standards: prompt.includes("- Standards first:") && prompt.includes("Powertools for AWS Lambda") }).toEqual({ id, standards: true })
      expect({ id, testing: prompt.includes("- Tests (`quality-testing`") && prompt.includes("only checks code is gone") }).toEqual({ id, testing: true })
    }
  })
})

describe("mcpCopies", () => {
  test("copies common/.mcp.json to the root of each harness tree", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-mcp-"))
    try {
      mkdirSync(path.join(dir, "common"))
      writeFileSync(path.join(dir, "common", ".mcp.json"), '{"mcpServers":{}}')
      expect(mcpCopies(dir, ["opencode", "claude"])).toEqual([
        { file: path.join(dir, "opencode", ".mcp.json"), contents: '{"mcpServers":{}}' },
        { file: path.join(dir, "claude", ".mcp.json"), contents: '{"mcpServers":{}}' },
      ])
      expect(mcpCopies(path.join(dir, "none"), ["opencode"])).toEqual([])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
