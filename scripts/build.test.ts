describe("composeAgents", () => {
  const plugin = () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-agents-"))
    mkdirSync(path.join(dir, "agents.src"))
    mkdirSync(path.join(dir, "common", "agents"), { recursive: true })
    writeFileSync(path.join(dir, "agents.src", "rev.md"), "---\nmode: subagent\n---\nIntro.\n{{include core}}\n")
    return dir
  }
  const read = () => "<!-- part: a -->\nRule A."
  const composed = "---\n# Generated by scripts/build.ts from agents.src/rev.md. Do not edit.\nmode: subagent\n---\nIntro.\nRule A.\n"

  test("composes agents.src/<id>.md into common/agents/<id>.md with the generated comment", () => {
    const dir = plugin()
    try {
      expect(composeAgents(dir, false, read)).toEqual([{ file: path.join(dir, "common", "agents", "rev.md"), contents: composed, hints: {} }])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("takes the x-omp-* hints out of the OpenCode form and returns them", () => {
    const dir = plugin()
    try {
      writeFileSync(path.join(dir, "agents.src", "rev.md"), '---\nx-omp-model: "@plan, @slow"\nmode: subagent\nx-omp-tools: github\n---\nIntro.\n{{include core}}\n')
      expect(composeAgents(dir, false, read)).toEqual([
        { file: path.join(dir, "common", "agents", "rev.md"), contents: composed, hints: { model: "@plan, @slow", tools: ["github"] } },
      ])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a plugin that also ships to Claude Code gets the OpenCode form, <id>.opencode.md", () => {
    const dir = plugin()
    try {
      expect(composeAgents(dir, true, read).map((output) => path.basename(output.file))).toEqual(["rev.opencode.md"])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a pi agent variant is not treated as an OpenCode or OMP agent", () => {
    const dir = plugin()
    try {
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(dir, "agents.src", "rev.md"), '---\ndescription: "Reviewer"\nmode: subagent\n---\nIntro.\n{{include core}}\n')
      writeFileSync(path.join(agents, "rev.pi.md"), "---\ntools: read\n---\nPi only")
      expect(orphanAgents(dir, [])).toEqual([])
      const composed = composeAgents(dir, false, read)
      const texts = agentTexts(dir, false, composed)
      expect([...texts.keys()]).toEqual(["rev"])
      expect(ompAgents(dir, false, texts, composed).map((agent) => agent.id)).toEqual(["rev"])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a composed agent without a source is an orphan; a hand-written agent and a translation are not", () => {
    const dir = plugin()
    try {
      const outputs = composeAgents(dir, true, read)
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(agents, "gone.opencode.md"), "---\n# Generated by scripts/build.ts from agents.src/gone.md. Do not edit.\n---\nx")
      writeFileSync(path.join(agents, "own.opencode.md"), "---\nmode: subagent\n---\nx")
      writeFileSync(path.join(agents, "rev.claude.md"), "---\n# Generated by scripts/build.ts from common/agents/rev.opencode.md. Do not edit.\n---\nx")
      writeFileSync(path.join(agents, "rev.omp.md"), "---\n# Generated by scripts/build.ts from common/agents/rev.opencode.md. Do not edit.\n---\nx")
      expect(orphanAgents(dir, outputs)).toEqual([path.join(agents, "gone.opencode.md")])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("agentTexts reads hand-written agents by id and lets a composed agent replace its file", () => {
    const dir = plugin()
    try {
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(agents, "own.opencode.md"), "own")
      writeFileSync(path.join(agents, "rev.opencode.md"), "stale")
      writeFileSync(path.join(agents, "own.claude.md"), "translated")
      const texts = agentTexts(dir, true, composeAgents(dir, true, read))
      expect(Object.fromEntries(texts)).toEqual({ own: "own", rev: composed })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("agentTexts leaves out an orphaned composed agent", () => {
    const dir = plugin()
    try {
      writeFileSync(path.join(dir, "common", "agents", "gone.opencode.md"), "---\n# Generated by scripts/build.ts from agents.src/gone.md. Do not edit.\n---\nx")
      expect([...agentTexts(dir, true, composeAgents(dir, true, read)).keys()]).toEqual(["rev"])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("ompAgents translates every agent text into common/agents/<id>.omp.md with its source's hints", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-omp-"))
    try {
      const opencode = "---\ndescription: \"Edits.\"\nmode: subagent\nrequest:\n  headers:\n    x-opencode-model-role: strong\n---\nBody.\n"
      const agents = path.join(dir, "common", "agents")
      const hinted = { file: path.join(agents, "a.opencode.md"), contents: opencode, hints: { model: "@plan, @slow" } }
      const [fromClaude] = ompAgents(dir, true, new Map([["a", opencode]]), [hinted])
      const [plain] = ompAgents(dir, false, new Map([["b", opencode]]))
      expect([fromClaude?.id, fromClaude?.file, plain?.file]).toEqual(["a", path.join(agents, "a.omp.md"), path.join(agents, "b.omp.md")])
      expect(fromClaude?.contents).toContain('\nmodel: "@plan, @slow"\n')
      expect(plain?.contents).toBe(
        `---\n# Generated by scripts/build.ts from plugins/${path.basename(dir)}/common/agents/b.md. Do not edit.\nname: b\ndescription: "Edits."\nmodel: "@slow"\n---\nBody.\n`,
      )
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("ompAgents keeps a hand-written <id>.omp.md rather than translating over it", () => {
    const dir = plugin()
    try {
      writeFileSync(path.join(dir, "common", "agents", "rev.omp.md"), "---\nname: rev\n---\nmine")
      expect(ompAgents(dir, false, new Map([["rev", "---\ndescription: d\n---\n"]]))).toEqual([])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("a generated OMP agent the build no longer produces is stale; a hand-written one is kept", () => {
    const dir = plugin()
    try {
      const agents = path.join(dir, "common", "agents")
      writeFileSync(path.join(agents, "gone.omp.md"), "---\n# Generated by scripts/build.ts from common/agents/gone.md. Do not edit.\n---\nx")
      writeFileSync(path.join(agents, "own.omp.md"), "---\nname: own\n---\nx")
      writeFileSync(path.join(agents, "rev.omp.md"), "---\n# Generated by scripts/build.ts from common/agents/rev.md. Do not edit.\n---\nx")
      expect(staleOmpAgents(dir, [{ file: path.join(agents, "rev.omp.md"), contents: "" }])).toEqual([path.join(agents, "gone.omp.md")])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("every shipped agents.src file composes to its committed common/agents file", () => {
    for (const name of ["agent-coder", "agent-reviewer", "delivery", "design", "journeys", "modes", "quality", "speckit"]) {
      const dir = path.join(plugins, name)
      const build = readBuild(dir)
      for (const output of composeAgents(dir, build?.claude)) expect(readFileSync(output.file, "utf8")).toBe(output.contents)
    }
  })

  const shipped = (plugin: string, id: string) => {
    const dir = path.join(plugins, plugin, "common", "agents")
    return readFileSync(path.join(dir, readBuild(path.join(plugins, plugin))?.claude ? `${id}.opencode.md` : `${id}.md`), "utf8")
  }

  test("the composed coder prompt carries the quality line", () => {
    const prompt = shipped("agent-coder", "coder")
    expect(prompt).toContain("a summary of `quality-code-policy`, which you load before code; where they differ the skill wins")
    expect(prompt).toContain("only for new behavior")
  })

  test("the coder and the delivery implementers compose the coding-core method", () => {
    for (const [plugin, id] of [
      ["agent-coder", "coder"],
      ["delivery", "implementer"],
      ["delivery", "implementer-high"],
    ]) {
      const source = readFileSync(path.join(plugins, plugin as string, "agents.src", `${id}.md`), "utf8")
      expect({ id, includes: source.includes("{{include coding-core: method}}") }).toEqual({ id, includes: true })
    }
  })

  test("every code reviewer composes the test-change rules and the standards and testing parts", () => {
    for (const [plugin, id] of [
      ["agent-reviewer", "code-reviewer"],
      ["agent-reviewer", "pr-reviewer"],
      ["delivery", "pr-reviewer"],
    ]) {
      const prompt = shipped(plugin as string, id as string)
      expect({ id, rules: prompt.includes("MUST Map the test diff to the code diff") && prompt.includes("maintenance, not tampering") }).toEqual({ id, rules: true })
      expect({ id, standards: prompt.includes("- Standards first:") && prompt.includes("- Tests (`quality-testing`") }).toEqual({ id, standards: true })
    }
  })

  test("every code-writing agent composes the engineering and testing standards", () => {
    for (const [plugin, id] of [
      ["agent-coder", "coder"],
      ["delivery", "implementer"],
      ["delivery", "implementer-high"],
      ["design", "ui-implementer"],
    ]) {
      const prompt = shipped(plugin as string, id as string)
      expect({ id, standards: prompt.includes("- Standards first:") && prompt.includes("Powertools for AWS Lambda") }).toEqual({ id, standards: true })
      expect({ id, testing: prompt.includes("- Tests (`quality-testing`") && prompt.includes("only checks code is gone") }).toEqual({ id, testing: true })
    }
  })
})

