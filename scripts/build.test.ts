import { describe, expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { isTranslatedAgentFile } from "./agent-files.ts"
import { agentTexts, buildPlugin, composeAgents, mcpCopies, ompAgents, ompExtensionCopies, orphanAgents, readBuild, selectPlugins, stale, staleOmpAgents } from "./build.ts"

const plugins = path.resolve(import.meta.dir, "../plugins")
const session = path.join(plugins, "session")
const statusline = path.join(plugins, "statusline")
const beads = path.join(plugins, "beads")

describe("buildPlugin", () => {
  test("inlines the shared lib and keeps host modules external", async () => {
    const outputs = await buildPlugin(session)
    const bundle = outputs.find((output) => output.file === path.join(session, "opencode/dist/index.js"))
    expect(bundle?.contents).toContain('from "@opencode/plugin"')
    expect(bundle?.contents).not.toContain("@srobroek/opencode-lib")
    expect(bundle?.contents).toContain("function parsedInvocations(")
  })

  test("writes a root shim for each entry", async () => {
    const outputs = await buildPlugin(session)
    const shim = outputs.find((output) => output.file === path.join(session, "opencode/index.js"))
    expect(shim?.contents).toContain('export { default } from "./dist/index.js"')
  })

  test("compiles TSX with the OpenTUI Solid transform and keeps the TUI runtime external", async () => {
    const outputs = await buildPlugin(statusline)
    const bundle = outputs.find((output) => output.file === path.join(statusline, "opencode/dist/tui.js"))
    expect(bundle?.contents).toContain('from "@opentui/solid"')
    expect(bundle?.contents).toContain("createElement")
    expect(bundle?.contents).toContain('from "solid-js"')
    expect(bundle?.contents).not.toContain("react")
    const shim = outputs.find((output) => output.file === path.join(statusline, "opencode/tui.js"))
    expect(shim?.contents).toContain('export { default } from "./dist/tui.js"')
  })

  test("bundles a Claude Code entry into claude/dist without a shim", async () => {
    const outputs = await buildPlugin(beads)
    expect(outputs.some((output) => output.file === path.join(beads, "claude/dist/claude-hook.js"))).toBe(true)
    expect(outputs.some((output) => output.file === path.join(beads, "opencode/dist/claude-hook.js"))).toBe(false)
    expect(outputs.some((output) => output.file === path.join(beads, "claude-hook.js") || output.file === path.join(beads, "opencode/claude-hook.js"))).toBe(false)
  })

  test("skips a directory without a package.json", async () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-empty-"))
    try {
      expect(await buildPlugin(dir)).toEqual([])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("bundles pi entries with host modules external and shared lib inlined", async () => {
    const outputs = await buildPlugin(path.resolve(plugins, "trunk-dev"))
    const bundle = outputs.find((output) => output.file.endsWith("/pi/extensions/skip-ci.js"))
    expect(bundle?.contents).toContain('from "@earendil-works/pi-coding-agent"')
    expect(bundle?.contents).not.toContain("@srobroek/opencode-lib")
    expect(bundle?.contents).toContain("function scanShell(")
    expect(bundle?.contents).toContain("skip_ci_default as default")
  })

  test("a plugin listing omp ships each pi bundle unchanged in omp/extensions", async () => {
    const dir = path.resolve(plugins, "code-challenge")
    const outputs = await buildPlugin(dir)
    const pi = outputs.find((output) => output.file === path.join(dir, "pi/extensions/index.js"))
    const omp = outputs.find((output) => output.file === path.join(dir, "omp/extensions/index.js"))
    expect(pi?.contents.startsWith("// @bun\n// Generated by scripts/build.ts. Do not edit.\n")).toBe(true)
    expect(omp?.contents).toBe(pi?.contents as string)
    expect(pi?.contents).not.toContain("@srobroek/opencode-lib")
    expect(pi?.contents).not.toContain("@opencode/plugin")
    expect(pi?.contents).not.toContain("@earendil-works/")
    expect(pi?.contents).toContain('"challenge_scan"')
  })

  test("a plugin not listing omp gets no OMP copies", () => {
    const bundles = [{ file: "/p/x/pi/extensions/a.js", contents: "a" }]
    expect(ompExtensionCopies("/p/x", ["opencode", "claude"], bundles)).toEqual([])
    expect(ompExtensionCopies("/p/x", ["opencode", "omp"], bundles)).toEqual([{ file: "/p/x/omp/extensions/a.js", contents: "a" }])
  })
})

describe("readBuild", () => {
  const manifest = (key: unknown) => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-manifest-"))
    writeFileSync(path.join(dir, "package.json"), JSON.stringify({ name: "x", "agent-plugins": key }))
    return dir
  }

  test("reads the harnesses, entries and Claude Code agent selection", () => {
    const dir = manifest({ harnesses: ["opencode", "claude"], entries: { index: "index" }, claudeEntries: { hook: "claude-hook" }, claudeAgents: ["a"] })
    try {
      expect(readBuild(dir)).toEqual({
        claude: true,
        harnesses: ["opencode", "claude"],
        entries: { index: "index" },
        claudeEntries: { hook: "claude-hook" },
        piEntries: {},
        claudeAgents: ["a"],
      })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("an OpenCode-only plugin without entries builds nothing", () => {
    const dir = manifest({ harnesses: ["opencode"] })
    try {
      expect(readBuild(dir)).toEqual({ claude: false, harnesses: ["opencode"], entries: {}, claudeEntries: {}, piEntries: {} })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("rejects an entries map that does not name source files", () => {
    const dir = manifest({ harnesses: ["opencode"], entries: { index: 1 } })
    try {
      expect(() => readBuild(dir)).toThrow('"agent-plugins.entries" must map names to source file names')
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("reads pi entry mappings and defaults them to empty", () => {
    const dir = manifest({ harnesses: ["pi"], piEntries: { advice: "advice" } })
    try {
      expect(readBuild(dir)?.piEntries).toEqual({ advice: "advice" })
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
    const empty = manifest({ harnesses: ["opencode"] })
    try {
      expect(readBuild(empty)?.piEntries).toEqual({})
    } finally {
      rmSync(empty, { recursive: true, force: true })
    }
  })

})

describe("stale pi bundles", () => {
  test("flags stale generated bundles but leaves hand-authored extensions alone", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "build-pi-stale-"))
    const extensions = path.join(dir, "pi", "extensions")
    mkdirSync(extensions, { recursive: true })
    const generated = path.join(extensions, "old.js")
    const handAuthored = path.join(extensions, "custom.js")
    writeFileSync(generated, "// @bun\n// Generated by scripts/build.ts. Do not edit.\nexport default () => {}\n")
    writeFileSync(handAuthored, "export default () => {}\n")
    try {
      expect(stale(dir, [])).toEqual([generated])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

