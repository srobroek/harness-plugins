import { describe, expect, test } from "bun:test"
import { MODEL_TIER_ALIASES, MODEL_TIERS } from "../lib/src/model-roles.ts"
import { parseFrontmatter } from "./convert-agent.ts"
import { droppedComment, OMP_ROLES, ompModel, ompNameConflicts, ompTools, readOnlyShell, splitOmpHints, translateOmpAgent } from "./omp-agents.ts"
import type { Rule } from "./opencode-permissions.ts"

const rule = (action: string, resource: string, effect: Rule["effect"]): Rule => ({ action, resource, effect })
const denyAll = rule("*", "*", "deny")

function agent(rules: Rule[], body = "\n# Prompt\n\nDo the thing.\n", tier = "cheap"): string {
  const permissions = rules
    .map(({ action, resource, effect }) => `  - action: "${action}"\n    resource: "${resource}"\n    effect: ${effect}`)
    .join("\n")
  return `---\n# Generated by scripts/build.ts from agents.src/x.md. Do not edit.\ndescription: "Edits things."\nmode: subagent\nsteps: 60\nhidden: true\ncolor: "#ff0000"\nmodel: "amazon-bedrock/x#high"\nrequest:\n  headers:\n    x-opencode-model-role: ${tier}\npermissions:\n${permissions}\n---\n${body}`
}

describe("ompModel", () => {
  test("maps each tier onto OMP role aliases, built-in roles first", () => {
    expect(Object.fromEntries(MODEL_TIERS.map((tier) => [tier, ompModel(tier)]))).toEqual({
      cheap: "@smol",
      standard: "@task",
      strong: "@slow",
      reviewer: "@challenger, @slow",
      orchestrate: "@orchestrate, @slow",
    })
  })

  test("each tier's first role is the tier itself or an old role name of that tier", () => {
    for (const tier of MODEL_TIERS) {
      const first = OMP_ROLES[tier][0] as string
      expect({ tier, first, ok: first === tier || MODEL_TIER_ALIASES[first] === tier }).toEqual({ tier, first, ok: true })
    }
  })

  test("an old role name maps through its tier, default inherits, and no header writes no model", () => {
    expect(ompModel("judge")).toBe("@challenger, @slow")
    expect(ompModel("default")).toBeUndefined()
    expect(ompModel(undefined)).toBeUndefined()
  })

  test("an unknown tier throws", () => {
    expect(() => ompModel("fastest", "agents/x.md")).toThrow('agents/x.md: x-opencode-model-role "fastest" is not a model tier')
  })
})

describe("ompTools", () => {
  test("turns the unrestricted allows of a deny-all-first list into OMP built-ins", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("grep", "*", "allow"),
      rule("glob", "*", "allow"),
      rule("lsp_*", "*", "allow"),
      rule("edit", "*", "allow"),
      rule("shell", "*", "allow"),
      rule("execute", "*", "allow"),
      rule("websearch", "*", "allow"),
    ])
    expect(out).toEqual({
      tools: ["read", "grep", "ast_grep", "glob", "lsp", "edit", "write", "ast_edit", "bash", "eval", "web_search"],
      dropped: [],
    })
  })

  test("no rules keeps OMP's default tools", () => {
    expect(ompTools([])).toEqual({ dropped: [] })
  })

  test("a list without a deny-all rule starts from OpenCode's allow-everything default", () => {
    expect(ompTools([rule("websearch", "*", "deny"), rule("subagent", "*", "deny"), rule("skill", "*", "deny")])).toEqual({
      tools: ["read", "grep", "ast_grep", "glob", "lsp", "edit", "write", "ast_edit", "bash", "eval"],
      dropped: [],
    })
    expect(ompTools([rule("read", "*", "allow")]).spawns).toBe("*")
  })

  test("keeps a tool whose per-resource rules OMP cannot hold, and leaves out one only they allow", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("read", "*.env", "ask"),
      rule("shell", "git diff *", "allow"),
    ])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped).toEqual([
      { action: "read", rule: "ask read(*.env)", reason: "OMP has no per-resource rules; the tool is kept" },
      { action: "shell", rule: "allow shell(git diff *)", reason: "OMP has no per-resource rules; the tool is left out" },
    ])
  })

  test("an unrestricted ask leaves the tool out", () => {
    const out = ompTools([denyAll, rule("read", "*", "allow"), rule("edit", "*", "ask")])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped).toEqual([{ action: "edit", rule: "ask edit", reason: "OMP has no per-agent ask; left out" }])
  })

  test("named subagent allows become spawns with OMP agent names, plus the task tool", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("subagent", "*", "deny"),
      rule("subagent", "explore", "allow"),
      rule("subagent", "general", "allow"),
      rule("subagent", "mechanic", "allow"),
      rule("subagent", "mechanic", "deny"),
      rule("subagent", "design-*", "allow"),
    ])
    expect(out.tools).toEqual(["read", "task"])
    expect(out.spawns).toBe("scout, task")
    expect(out.dropped).toEqual([{ action: "subagent", rule: "allow subagent(design-*)", reason: "OMP spawns takes agent names, not globs" }])
  })

  test("an unrestricted subagent allow spawns every agent and drops per-agent denies", () => {
    const out = ompTools([denyAll, rule("read", "*", "allow"), rule("subagent", "*", "allow"), rule("subagent", "self", "deny")])
    expect(out.spawns).toBe("*")
    expect(out.dropped).toEqual([{ action: "subagent", rule: "deny subagent(self)", reason: "OMP spawns cannot exclude an agent" }])
  })

  test("drops allows of actions without an OMP built-in, with the reason, and ignores their denies", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("webfetch", "*", "allow"),
      rule("skill", "quality-*", "allow"),
      rule("external_directory", "*", "ask"),
      rule("repomix_pack", "*", "allow"),
      rule("question", "*", "deny"),
    ])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped.map((drop) => [drop.rule, drop.reason])).toEqual([
      ["allow webfetch", "OMP fetches URLs with read"],
      ["allow skill(quality-*)", "OMP has no per-agent skill filter"],
      ["ask external_directory", "OMP has no per-agent directory rule"],
      ["allow repomix_pack", "no OMP built-in tool; tools filters built-ins only"],
    ])
  })

  test("an allowlist nothing survives stays empty rather than falling back to the defaults", () => {
    expect(ompTools([denyAll, rule("shell", "gh pr view *", "allow")]).tools).toEqual([])
  })
})

describe("droppedComment", () => {
  test("groups drops by reason and counts an action with many rules", () => {
    const many = Array.from({ length: 7 }, (_, index) => ({ action: "shell", rule: `deny shell(c${index})`, reason: "r1" }))
    expect(droppedComment([{ action: "read", rule: "ask read(*.env)", reason: "r1" }, ...many, { action: "skill", rule: "allow skill(a)", reason: "r2" }])).toEqual([
      "# OMP cannot express these OpenCode permissions; they are dropped:",
      "#   r1: ask read(*.env), 7 shell rules",
      "#   r2: allow skill(a)",
    ])
  })

  test("writes nothing when nothing is dropped", () => {
    expect(droppedComment([])).toEqual([])
  })
})

describe("translateOmpAgent", () => {
  test("keeps only OMP frontmatter keys, records the losses, and passes the body through unchanged", () => {
    const body = "\nYou edit.\n\n## Rules\n\n- MUST use `grep`.\n"
    const out = translateOmpAgent(
      "mechanic",
      agent([denyAll, rule("read", "*", "allow"), rule("subagent", "explore", "allow"), rule("skill", "lang-*", "allow")], body),
      "plugins/p/common/agents/mechanic.md",
    )
    const { data, body: outBody } = parseFrontmatter(out.contents)
    expect(data).toEqual({
      name: "mechanic",
      description: "Edits things.",
      tools: "read, task",
      spawns: "scout",
      model: "@smol",
    })
    expect(outBody).toBe(body)
    expect(out.contents.split("\n").slice(0, 4)).toEqual([
      "---",
      "# Generated by scripts/build.ts from plugins/p/common/agents/mechanic.md. Do not edit.",
      "# OMP cannot express these OpenCode permissions; they are dropped:",
      "#   OMP has no per-agent skill filter: allow skill(lang-*)",
    ])
  })

  test("writes an empty allowlist as [], which OMP reads as no built-in tools", () => {
    const out = translateOmpAgent("pr", agent([denyAll, rule("shell", "gh pr diff *", "allow")]))
    expect(out.contents).toContain("\ntools: []\n")
    expect(parseFrontmatter(out.contents).data.tools).toEqual([])
  })

  test("a missing description throws", () => {
    expect(() => translateOmpAgent("x", "---\nmode: subagent\n---\nBody.\n", "agents/x.md")).toThrow("agents/x.md: description is required")
  })
})

describe("translateOmpAgent with hints", () => {
  const reviewer = agent([denyAll, rule("read", "*", "allow"), rule("shell", "*", "allow"), rule("shell", "git push *", "deny")], "\nReview.\n", "reviewer")

  test("x-omp-model replaces the tier's roles", () => {
    const out = translateOmpAgent("arch", reviewer, "agents/arch.md", { model: "@architect, @slow", shell: "it reads git log" })
    expect(parseFrontmatter(out.contents).data.model).toBe("@architect, @slow")
  })

  test("a read-only agent loses bash unless x-omp-shell says why, and the comment records either way", () => {
    const dropped = translateOmpAgent("rev", reviewer, "agents/rev.md")
    expect(parseFrontmatter(dropped.contents).data.tools).toBe("read")
    expect(dropped.contents.split("\n")[2]).toBe("# Read-only: bash is left out: OMP cannot limit it to read-only commands.")
    const kept = translateOmpAgent("rev", reviewer, "agents/rev.md", { shell: "it reads the patch with git diff" })
    expect(parseFrontmatter(kept.contents).data.tools).toBe("read, bash")
    expect(kept.contents.split("\n")[2]).toBe("# Read-only, but keeps bash: it reads the patch with git diff")
  })

  test("x-omp-tools adds OMP tools no permission names", () => {
    const out = translateOmpAgent("pr", agent([denyAll, rule("shell", "gh pr diff *", "allow")]), "agents/pr.md", { tools: ["github"] })
    expect(parseFrontmatter(out.contents).data.tools).toBe("github")
  })

  test("hints that do not fit the agent throw", () => {
    const noRules = "---\ndescription: d\n---\nBody.\n"
    expect(() => translateOmpAgent("x", noRules, "agents/x.md", { tools: ["github"] })).toThrow("agents/x.md: x-omp-tools and x-omp-shell need a permissions list")
    expect(() => translateOmpAgent("x", reviewer, "agents/x.md", { tools: ["read"] })).toThrow("agents/x.md: x-omp-tools repeats read")
  })
})

describe("splitOmpHints", () => {
  test("takes the x-omp-* lines out of the frontmatter and leaves the rest byte for byte", () => {
    const source = '---\ndescription: d\nx-omp-model: "@plan, @slow"\nx-omp-shell: "it runs bd"\nx-omp-tools: github, todo\nmode: subagent\n---\nx-omp-model: body text stays\n'
    expect(splitOmpHints(source, "agents.src/a.md")).toEqual({
      source: "---\ndescription: d\nmode: subagent\n---\nx-omp-model: body text stays\n",
      hints: { model: "@plan, @slow", shell: "it runs bd", tools: ["github", "todo"] },
    })
  })

  test("a source without hints or frontmatter comes back unchanged", () => {
    for (const source of ["---\ndescription: d\n---\nBody.\n", "Body only.\n"]) expect(splitOmpHints(source, "a.md")).toEqual({ source, hints: {} })
  })

  test("an unknown key, a repeat or a malformed value throws", () => {
    const head = (lines: string) => `---\n${lines}\n---\n`
    expect(() => splitOmpHints(head("x-omp-modle: x"), "a.md")).toThrow("a.md: unknown key x-omp-modle")
    expect(() => splitOmpHints(head("x-omp-shell: a\nx-omp-shell: b"), "a.md")).toThrow("a.md: x-omp-shell is set twice")
    expect(() => splitOmpHints(head('x-omp-model: "architect"'), "a.md")).toThrow('a.md: x-omp-model must list OMP roles on one line, as "@role, @role"')
    expect(() => splitOmpHints(head("x-omp-tools:\n  - github"), "a.md")).toThrow("a.md: x-omp-tools must list distinct OMP tool names")
    expect(() => splitOmpHints(head("x-omp-tools: github, github"), "a.md")).toThrow("a.md: x-omp-tools must list distinct OMP tool names")
    expect(() => splitOmpHints(head("x-omp-shell: "), "a.md")).toThrow("a.md: x-omp-shell must give the reason on one line")
  })
})

describe("readOnlyShell", () => {
  test("leaves bash and eval out of an agent without an edit tool", () => {
    expect(readOnlyShell(["read", "bash", "eval", "task"], undefined)).toEqual({
      tools: ["read", "task"],
      comment: ["# Read-only: bash and eval are left out: OMP cannot limit them to read-only commands."],
    })
  })

  test("a reason keeps them and is recorded", () => {
    expect(readOnlyShell(["read", "eval"], "it drives the browser")).toEqual({
      tools: ["read", "eval"],
      comment: ["# Read-only, but keeps eval: it drives the browser"],
    })
  })

  test("an agent that edits, or has no shell, is untouched, and a reason on it throws", () => {
    expect(readOnlyShell(["read", "edit", "write", "bash"], undefined)).toEqual({ tools: ["read", "edit", "write", "bash"], comment: [] })
    expect(readOnlyShell(["read"], undefined)).toEqual({ tools: ["read"], comment: [] })
    expect(() => readOnlyShell(["read", "edit", "bash"], "why", "agents/x.md")).toThrow("agents/x.md: x-omp-shell applies only to a read-only agent")
    expect(() => readOnlyShell(["read"], "why", "agents/x.md")).toThrow("agents/x.md: x-omp-shell applies only to a read-only agent")
  })
})

describe("ompNameConflicts", () => {
  const file = (where: string, tools = "read") => `---\n# Generated by scripts/build.ts from ${where}. Do not edit.\nname: code-researcher\ntools: ${tools}\n---\nBody.\n`

  test("copies of one agent that differ only in their source comment pass", () => {
    expect(
      ompNameConflicts([
        { plugin: "agent-researcher", id: "code-researcher", contents: file("plugins/agent-researcher/common/agents/code-researcher.md") },
        { plugin: "delivery", id: "code-researcher", contents: file("plugins/delivery/common/agents/code-researcher.md") },
      ]),
    ).toEqual([])
  })

  test("copies that differ otherwise, and a bundled OMP agent name, are reported", () => {
    expect(
      ompNameConflicts([
        { plugin: "agent-researcher", id: "code-researcher", contents: file("a") },
        { plugin: "delivery", id: "code-researcher", contents: file("b", "read, bash") },
        { plugin: "agent-reviewer", id: "security-reviewer", contents: file("c") },
      ]),
    ).toEqual([
      "agent-reviewer: agent security-reviewer would replace OMP's bundled security-reviewer; rename it",
      "agent code-researcher: the OMP files of agent-researcher and delivery differ, and OMP loads only the first; make them match",
    ])
  })
})
