import { describe, expect, test } from "bun:test"
import { MODEL_TIER_ALIASES, MODEL_TIERS } from "../lib/src/model-roles.ts"
import { parseFrontmatter } from "./convert-agent.ts"
import { droppedComment, OMP_ROLES, ompModel, ompTools, translateOmpAgent } from "./omp-agents.ts"
import type { Rule } from "./opencode-permissions.ts"

const rule = (action: string, resource: string, effect: Rule["effect"]): Rule => ({ action, resource, effect })
const denyAll = rule("*", "*", "deny")

function agent(rules: Rule[], body = "\n# Prompt\n\nDo the thing.\n", tier = "cheap"): string {
  const permissions = rules
    .map(({ action, resource, effect }) => `  - action: "${action}"\n    resource: "${resource}"\n    effect: ${effect}`)
    .join("\n")
  return `---\n# Generated by scripts/build.ts from agents.src/x.md. Do not edit.\ndescription: "Edits things."\nmode: subagent\nsteps: 60\nhidden: true\ncolor: "#ff0000"\nmodel: "amazon-bedrock/x#high"\nrequest:\n  headers:\n    x-opencode-model-role: ${tier}\npermissions:\n${permissions}\n---\n${body}`
}

describe("ompModel", () => {
  test("maps each tier onto OMP role aliases, built-in roles first", () => {
    expect(Object.fromEntries(MODEL_TIERS.map((tier) => [tier, ompModel(tier)]))).toEqual({
      cheap: "@smol",
      standard: "@task",
      strong: "@slow",
      reviewer: "@challenger, @slow",
      orchestrate: "@orchestrate, @slow",
    })
  })

  test("each tier's first role is the tier itself or an old role name of that tier", () => {
    for (const tier of MODEL_TIERS) {
      const first = OMP_ROLES[tier][0] as string
      expect({ tier, first, ok: first === tier || MODEL_TIER_ALIASES[first] === tier }).toEqual({ tier, first, ok: true })
    }
  })

  test("an old role name maps through its tier, default inherits, and no header writes no model", () => {
    expect(ompModel("judge")).toBe("@challenger, @slow")
    expect(ompModel("default")).toBeUndefined()
    expect(ompModel(undefined)).toBeUndefined()
  })

  test("an unknown tier throws", () => {
    expect(() => ompModel("fastest", "agents/x.md")).toThrow('agents/x.md: x-opencode-model-role "fastest" is not a model tier')
  })
})

describe("ompTools", () => {
  test("turns the unrestricted allows of a deny-all-first list into OMP built-ins", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("grep", "*", "allow"),
      rule("glob", "*", "allow"),
      rule("lsp_*", "*", "allow"),
      rule("edit", "*", "allow"),
      rule("shell", "*", "allow"),
      rule("execute", "*", "allow"),
      rule("websearch", "*", "allow"),
    ])
    expect(out).toEqual({
      tools: ["read", "grep", "ast_grep", "glob", "lsp", "edit", "write", "ast_edit", "bash", "eval", "web_search"],
      dropped: [],
    })
  })

  test("no rules keeps OMP's default tools", () => {
    expect(ompTools([])).toEqual({ dropped: [] })
  })

  test("a list without a deny-all rule throws, since OMP has no tool denylist", () => {
    expect(() => ompTools([rule("shell", "*", "deny")], "agents/x.md")).toThrow("agents/x.md: OMP tools is an allowlist")
  })

  test("keeps a tool whose per-resource rules OMP cannot hold, and leaves out one only they allow", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("read", "*.env", "ask"),
      rule("shell", "git diff *", "allow"),
    ])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped).toEqual([
      { action: "read", rule: "ask read(*.env)", reason: "OMP has no per-resource rules; the tool is kept" },
      { action: "shell", rule: "allow shell(git diff *)", reason: "OMP has no per-resource rules; the tool is left out" },
    ])
  })

  test("an unrestricted ask leaves the tool out", () => {
    const out = ompTools([denyAll, rule("read", "*", "allow"), rule("edit", "*", "ask")])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped).toEqual([{ action: "edit", rule: "ask edit", reason: "OMP has no per-agent ask; left out" }])
  })

  test("named subagent allows become spawns with OMP agent names, plus the task tool", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("subagent", "*", "deny"),
      rule("subagent", "explore", "allow"),
      rule("subagent", "general", "allow"),
      rule("subagent", "mechanic", "allow"),
      rule("subagent", "mechanic", "deny"),
      rule("subagent", "design-*", "allow"),
    ])
    expect(out.tools).toEqual(["read", "task"])
    expect(out.spawns).toBe("scout, task")
    expect(out.dropped).toEqual([{ action: "subagent", rule: "allow subagent(design-*)", reason: "OMP spawns takes agent names, not globs" }])
  })

  test("an unrestricted subagent allow spawns every agent and drops per-agent denies", () => {
    const out = ompTools([denyAll, rule("read", "*", "allow"), rule("subagent", "*", "allow"), rule("subagent", "self", "deny")])
    expect(out.spawns).toBe("*")
    expect(out.dropped).toEqual([{ action: "subagent", rule: "deny subagent(self)", reason: "OMP spawns cannot exclude an agent" }])
  })

  test("drops allows of actions without an OMP built-in, with the reason, and ignores their denies", () => {
    const out = ompTools([
      denyAll,
      rule("read", "*", "allow"),
      rule("webfetch", "*", "allow"),
      rule("skill", "quality-*", "allow"),
      rule("external_directory", "*", "ask"),
      rule("repomix_pack", "*", "allow"),
      rule("question", "*", "deny"),
    ])
    expect(out.tools).toEqual(["read"])
    expect(out.dropped.map((drop) => [drop.rule, drop.reason])).toEqual([
      ["allow webfetch", "OMP fetches URLs with read"],
      ["allow skill(quality-*)", "OMP has no per-agent skill filter"],
      ["ask external_directory", "OMP has no per-agent directory rule"],
      ["allow repomix_pack", "no OMP built-in tool; tools filters built-ins only"],
    ])
  })

  test("an allowlist nothing survives stays empty rather than falling back to the defaults", () => {
    expect(ompTools([denyAll, rule("shell", "gh pr view *", "allow")]).tools).toEqual([])
  })
})

describe("droppedComment", () => {
  test("groups drops by reason and counts an action with many rules", () => {
    const many = Array.from({ length: 7 }, (_, index) => ({ action: "shell", rule: `deny shell(c${index})`, reason: "r1" }))
    expect(droppedComment([{ action: "read", rule: "ask read(*.env)", reason: "r1" }, ...many, { action: "skill", rule: "allow skill(a)", reason: "r2" }])).toEqual([
      "# OMP cannot express these OpenCode permissions; they are dropped:",
      "#   r1: ask read(*.env), 7 shell rules",
      "#   r2: allow skill(a)",
    ])
  })

  test("writes nothing when nothing is dropped", () => {
    expect(droppedComment([])).toEqual([])
  })
})

describe("translateOmpAgent", () => {
  test("keeps only OMP frontmatter keys, records the losses, and passes the body through unchanged", () => {
    const body = "\nYou edit.\n\n## Rules\n\n- MUST use `grep`.\n"
    const out = translateOmpAgent(
      "mechanic",
      agent([denyAll, rule("read", "*", "allow"), rule("subagent", "explore", "allow"), rule("skill", "lang-*", "allow")], body),
      "plugins/p/common/agents/mechanic.md",
    )
    const { data, body: outBody } = parseFrontmatter(out.contents)
    expect(data).toEqual({
      name: "mechanic",
      description: "Edits things.",
      tools: "read, task",
      spawns: "scout",
      model: "@smol",
    })
    expect(outBody).toBe(body)
    expect(out.contents.split("\n").slice(0, 4)).toEqual([
      "---",
      "# Generated by scripts/build.ts from plugins/p/common/agents/mechanic.md. Do not edit.",
      "# OMP cannot express these OpenCode permissions; they are dropped:",
      "#   OMP has no per-agent skill filter: allow skill(lang-*)",
    ])
  })

  test("writes an empty allowlist as [], which OMP reads as no built-in tools", () => {
    const out = translateOmpAgent("pr", agent([denyAll, rule("shell", "gh pr diff *", "allow")]))
    expect(out.contents).toContain("\ntools: []\n")
    expect(parseFrontmatter(out.contents).data.tools).toEqual([])
  })

  test("a missing description throws", () => {
    expect(() => translateOmpAgent("x", "---\nmode: subagent\n---\nBody.\n", "agents/x.md")).toThrow("agents/x.md: description is required")
  })
})
