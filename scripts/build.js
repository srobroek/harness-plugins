// Builds the parts of every plugin that harness-kit does not generate.
//
// OpenCode installs a plugin from its own directory only (a git `::path:` spec
// packs just that subdirectory), so the shared library (lib/) is inlined into
// each bundle. Modules the host provides at runtime stay external. For each
// entry the build also writes a root shim (`index.js`, `tui.js`, ...) because
// OpenCode loads a local plugin directory by file name, not through package.json
// exports. TSX sources get the OpenTUI Solid transform here, because OpenCode
// only compiles TSX outside node_modules.
//
// Per plugin, from the `agent-plugins` key of its package.json:
//   entries         { "<shim>": "<opencode/src file>" }  bundled to opencode/dist and opencode/<shim>.js
//   claudeEntries   { "<name>": "<opencode/src file>" }  bundled to claude/dist/<name>.js
//
// It also composes each `agents.src/<id>.md` into `common/agents/<id>.md` (`<id>.opencode.md`
// when the plugin also ships to Claude Code), inlining `{{include <fragment>}}` lines from
// lib/src/<fragment>.md, and writes the Claude Code files of scripts/build-claude.ts.
// It copies `common/.mcp.json` to each harness tree. `harness-kit build` then copies common/ into the harness trees.
//
//   bun scripts/build.ts                 build all plugins
//   bun scripts/build.ts <name>...       build only the named plugins (the release uses this)
//   bun scripts/build.ts --check [name]  fail when committed output is stale
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createSolidTransformPlugin } from "@opentui/solid/bun-plugin";
import { composeAgentFile, generatedComment } from "../lib/src/fragments.ts";
import { claudeOutputs, openCodeAgentFile, staleClaudeFiles } from "./build-claude.ts";
const HOST_MODULES = [
    "@opencode/plugin",
    "@opencode/plugin/*",
    "effect",
    "effect/*",
    "@opentui/*",
    "solid-js",
    "solid-js/*",
];
const SOURCE_EXTENSIONS = [".ts", ".tsx"];
const CONFIG_KEY = "agent-plugins";
const HEADER = "// Generated by scripts/build.ts. Do not edit.\n";
const root = path.resolve(import.meta.dir, "..");
const pluginsDir = path.join(root, "plugins");
export function readBuild(dir) {
    const manifestPath = path.join(dir, "package.json");
    if (!existsSync(manifestPath))
        return undefined;
    const where = `${path.relative(root, dir)}/package.json`;
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const own = manifest[CONFIG_KEY];
    if (typeof own !== "object" || own === null)
        throw new Error(`${where}: missing "${CONFIG_KEY}" key`);
    const map = (key) => {
        const value = own[key] ?? {};
        if (typeof value !== "object" || value === null || Object.values(value).some((name) => typeof name !== "string"))
            throw new Error(`${where}: "${CONFIG_KEY}.${key}" must map names to source file names`);
        return value;
    };
    const harnesses = Array.isArray(own.harnesses) ? own.harnesses : [];
    const claudeAgents = own.claudeAgents;
    return {
        claude: harnesses.includes("claude"),
        harnesses,
        entries: map("entries"),
        claudeEntries: map("claudeEntries"),
        ...(claudeAgents === undefined ? {} : { claudeAgents }),
    };
}
function sourceOf(dir, name, key) {
    const source = SOURCE_EXTENSIONS.map((ext) => path.join(dir, "opencode", "src", `${name}${ext}`)).find(existsSync);
    if (!source)
        throw new Error(`${path.relative(root, dir)}: no opencode/src/${name}.ts for entry "${key}"`);
    return source;
}
async function bundle(dir, items, tree) {
    if (items.length === 0)
        return [];
    const result = await Bun.build({
        entrypoints: items.map((item) => item.source),
        root: path.join(dir, "opencode", "src"),
        target: "bun",
        format: "esm",
        external: HOST_MODULES,
        splitting: false,
        minify: false,
        sourcemap: "none",
        plugins: [createSolidTransformPlugin()],
    });
    if (!result.success)
        throw new AggregateError(result.logs, `${path.relative(root, dir)}: build failed`);
    const outputs = [];
    for (const artifact of result.outputs) {
        if (artifact.kind !== "entry-point")
            continue;
        // Keep Bun's `// @bun` pragma on the first line; Bun only honours it there.
        const text = await artifact.text();
        const contents = text.startsWith("// @bun\n") ? `// @bun\n${HEADER}${text.slice(8)}` : HEADER + text;
        outputs.push({ file: path.join(dir, tree, "dist", artifact.path), contents });
    }
    return outputs;
}
/** The bundles of the OpenCode tree, with a root shim for each entry, and of the Claude Code tree. */
export async function buildPlugin(dir, build = readBuild(dir)) {
    if (build === undefined)
        return [];
    const opencode = Object.entries(build.entries).map(([shim, name]) => ({
        shim: `${shim}.js`,
        dist: `dist/${name}.js`,
        source: sourceOf(dir, name, shim),
    }));
    const claude = Object.entries(build.claudeEntries).map(([out, name]) => ({
        dist: `dist/${out}.js`,
        source: sourceOf(dir, name, out),
    }));
    const outputs = [...(await bundle(dir, opencode, "opencode")), ...(await bundle(dir, claude, "claude"))];
    for (const item of opencode) {
        outputs.push({
            file: path.join(dir, "opencode", item.shim),
            contents: `${HEADER}export { default } from "./${item.dist}"\nexport * from "./${item.dist}"\n`,
        });
    }
    return outputs;
}
/** `common/.mcp.json` is copied to the root of every harness tree: Claude Code reads it, and the OpenCode plugin reads the same servers. */
export function mcpCopies(dir, harnesses) {
    const source = path.join(dir, "common", ".mcp.json");
    if (!existsSync(source))
        return [];
    const contents = readFileSync(source, "utf8");
    return harnesses.map((harness) => ({ file: path.join(dir, harness, ".mcp.json"), contents }));
}
const AGENT_SOURCES = "agents.src";
/** The `common/agents/<id>.md` (`<id>.opencode.md` for a plugin with a Claude Code tree) composed from every `agents.src/<id>.md`. */
export function composeAgents(dir, claude = false, read) {
    const sources = path.join(dir, AGENT_SOURCES);
    if (!existsSync(sources))
        return [];
    return readdirSync(sources)
        .filter((name) => name.endsWith(".md"))
        .sort()
        .map((name) => ({
        file: path.join(dir, "common", "agents", openCodeAgentFile(name.slice(0, -3), claude)),
        contents: composeAgentFile(readFileSync(path.join(sources, name), "utf8"), `${AGENT_SOURCES}/${name}`, read),
    }));
}
/** Composed agent files whose source is gone: they carry the generated comment but no build produces them. */
export function orphanAgents(dir, outputs) {
    const agents = path.join(dir, "common", "agents");
    if (!existsSync(agents))
        return [];
    const expected = new Set(outputs.map((output) => output.file));
    return readdirSync(agents)
        .filter((name) => name.endsWith(".md") && !name.endsWith(".claude.md"))
        .map((name) => path.join(agents, name))
        .filter((file) => !expected.has(file))
        .filter((file) => readFileSync(file, "utf8").startsWith(`---\n${generatedComment(`${AGENT_SOURCES}/${path.basename(file).replace(/\.opencode\.md$/, ".md")}`)}\n`));
}
/** The OpenCode form of every agent of a plugin by id: composed, else hand-written in `common/agents/`. */
export function agentTexts(dir, claude, composed) {
    const texts = new Map();
    const agents = path.join(dir, "common", "agents");
    const suffix = claude ? ".opencode.md" : ".md";
    if (existsSync(agents)) {
        for (const name of readdirSync(agents)) {
            if (name.endsWith(".claude.md") || !name.endsWith(suffix))
                continue;
            texts.set(name.slice(0, -suffix.length), readFileSync(path.join(agents, name), "utf8"));
        }
    }
    for (const output of composed)
        texts.set(path.basename(output.file).slice(0, -suffix.length), output.contents);
    return texts;
}
function listFiles(dir) {
    if (!existsSync(dir))
        return [];
    return readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => path.join(entry.parentPath, entry.name));
}
const differs = (output) => !existsSync(output.file) || readFileSync(output.file, "utf8") !== output.contents;
/** Paths whose committed contents differ from a fresh build, or that the build no longer produces. */
export function stale(dir, outputs) {
    const expected = new Set(outputs.map((output) => output.file));
    const extra = ["opencode", "claude"].flatMap((tree) => listFiles(path.join(dir, tree, "dist"))).filter((file) => !expected.has(file));
    return [...outputs.filter(differs).map((output) => output.file), ...extra];
}
/** The plugin directories named in `only`, or all of them when it is empty; an unknown name throws. */
export function selectPlugins(dirs, only) {
    const unknown = only.filter((name) => !dirs.some((dir) => path.basename(dir) === name));
    if (unknown.length > 0)
        throw new Error(`unknown plugin: ${unknown.join(", ")}`);
    return only.length === 0 ? [...dirs] : dirs.filter((dir) => only.includes(path.basename(dir)));
}
async function main(check, only) {
    // Bun names source files relative to the working directory in its output.
    process.chdir(root);
    const dirs = readdirSync(pluginsDir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => path.join(pluginsDir, entry.name));
    const selected = selectPlugins(dirs, only);
    const problems = [];
    const warnings = [];
    for (const dir of selected) {
        const build = readBuild(dir);
        if (build === undefined)
            continue;
        const composed = composeAgents(dir, build.claude);
        const orphans = orphanAgents(dir, composed);
        const claude = build.claude
            ? claudeOutputs({ dir, agents: agentTexts(dir, true, composed), selected: build.claudeAgents }, (message) => warnings.push(message))
            : [];
        const generated = [...composed, ...claude, ...mcpCopies(dir, build.harnesses)];
        const bundles = await buildPlugin(dir, build);
        const staleClaude = staleClaudeFiles({ dir }, claude);
        if (check) {
            problems.push(...generated.filter(differs).map((output) => output.file), ...orphans, ...staleClaude, ...stale(dir, bundles));
            continue;
        }
        for (const file of [...orphans, ...staleClaude])
            rmSync(file);
        for (const tree of ["opencode", "claude"])
            rmSync(path.join(dir, tree, "dist"), { recursive: true, force: true });
        for (const output of [...generated, ...bundles]) {
            mkdirSync(path.dirname(output.file), { recursive: true });
            writeFileSync(output.file, output.contents);
        }
        if (generated.length + bundles.length > 0)
            console.log(`built ${path.relative(root, dir)}`);
    }
    for (const warning of warnings)
        console.warn(`warning: ${warning}`);
    if (problems.length > 0) {
        console.error("Build output is stale. Run `bun run build` and commit the result:");
        for (const file of problems)
            console.error(`  ${path.relative(root, file)}`);
        process.exit(1);
    }
}
if (import.meta.main) {
    const args = process.argv.slice(2);
    await main(args.includes("--check"), args.filter((arg) => !arg.startsWith("--")));
}
