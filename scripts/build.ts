// Builds the parts of every plugin that harness-kit does not generate.
//
// OpenCode installs a plugin from its own directory only (a git `::path:` spec
// packs just that subdirectory), so the shared library (lib/) is inlined into
// each bundle. Modules the host provides at runtime stay external. For each
// entry the build also writes a root shim (`index.js`, `tui.js`, ...) because
// OpenCode loads a local plugin directory by file name, not through package.json
// exports. TSX sources get the OpenTUI Solid transform here, because OpenCode
// only compiles TSX outside node_modules.
//
// Per plugin, from the `agent-plugins` key of its package.json:
//   entries         { "<shim>": "<opencode/src file>" }  bundled to opencode/dist and opencode/<shim>.js
//   claudeEntries   { "<name>": "<opencode/src file>" }  bundled to claude/dist/<name>.js
//   piEntries       { "<name>": "<pi-src file>" }  bundled to pi/extensions/<name>.js
//
// It also composes each `agents.src/<id>.md` into `common/agents/<id>.md` (`<id>.opencode.md`
// when the plugin also ships to Claude Code), inlining `{{include <fragment>}}` lines from
// lib/src/<fragment>.md, translates each composed agent into the OMP task agent
// `common/agents/<id>.omp.md` (scripts/omp-agents.ts), and writes the Claude Code files of
// scripts/build-claude.ts.
// It copies `common/.mcp.json` to each harness tree. `harness-kit build` then copies common/ into the harness trees.
//
//   bun scripts/build.ts                 build all plugins
//   bun scripts/build.ts <name>...       build only the named plugins (the release uses this)
//   bun scripts/build.ts --check [name]  fail when committed output is stale

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { createSolidTransformPlugin } from "@opentui/solid/bun-plugin"
import { composeAgentFile, generatedComment } from "../lib/src/fragments.ts"
import { isTranslatedAgentFile, ompAgentFile } from "./agent-files.ts"
import { claudeOutputs, openCodeAgentFile, staleClaudeFiles } from "./build-claude.ts"
import { translateOmpAgent } from "./omp-agents.ts"

const HOST_MODULES = [
  "@opencode/plugin",
  "@opencode/plugin/*",
  "effect",
  "effect/*",
  "@opentui/*",
  "solid-js",
  "solid-js/*",
]
const PI_HOST_MODULES = [
  "@earendil-works/pi-coding-agent",
  "@earendil-works/pi-agent-core",
  "@earendil-works/pi-ai",
  "@earendil-works/pi-ai/*",
  "@earendil-works/pi-tui",
  "typebox",
  "typebox/*",
]
const SOURCE_EXTENSIONS = [".ts", ".tsx"]
const CONFIG_KEY = "agent-plugins"
const HEADER = "// Generated by scripts/build.ts. Do not edit.\n"

const root = path.resolve(import.meta.dir, "..")
const pluginsDir = path.join(root, "plugins")

export type Output = { file: string; contents: string }

/** What a plugin's `agent-plugins` key says about its build. */
export type PluginBuild = {
  /** Whether the plugin ships a Claude Code tree. */
  claude: boolean
  /** Harness trees the plugin ships. */
  harnesses: string[]
  /** `{ shim: source name }` for the OpenCode tree. */
  entries: Record<string, string>
  /** `{ output name: source name }` for the Claude Code tree. */
  claudeEntries: Record<string, string>
  /** `{ extension name: pi-src source name }` for the pi tree. */
  piEntries: Record<string, string>
  /** Agents translated for Claude Code; every non-primary one when absent. */
  claudeAgents?: string[]
}

export function readBuild(dir: string): PluginBuild | undefined {
  const manifestPath = path.join(dir, "package.json")
  if (!existsSync(manifestPath)) return undefined
  const where = `${path.relative(root, dir)}/package.json`
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as Record<string, unknown>
  const own = manifest[CONFIG_KEY] as Record<string, unknown> | undefined
  if (typeof own !== "object" || own === null) throw new Error(`${where}: missing "${CONFIG_KEY}" key`)
  const map = (key: string): Record<string, string> => {
    const value = own[key] ?? {}
    if (typeof value !== "object" || value === null || Object.values(value).some((name) => typeof name !== "string"))
      throw new Error(`${where}: "${CONFIG_KEY}.${key}" must map names to source file names`)
    return value as Record<string, string>
  }
  const harnesses = Array.isArray(own.harnesses) ? (own.harnesses as string[]) : []
  const claudeAgents = own.claudeAgents as string[] | undefined
  return {
    claude: harnesses.includes("claude"),
    harnesses,
    entries: map("entries"),
    claudeEntries: map("claudeEntries"),
    piEntries: map("piEntries"),
    ...(claudeAgents === undefined ? {} : { claudeAgents }),
  }
}

type Entry = { shim?: string; dist: string; source: string }

function sourceOf(dir: string, name: string, key: string, sourceTree = "opencode/src"): string {
  const source = SOURCE_EXTENSIONS.map((ext) => path.join(dir, sourceTree, `${name}${ext}`)).find(existsSync)
  if (!source) throw new Error(`${path.relative(root, dir)}: no ${sourceTree}/${name}.ts for entry "${key}"`)
  return source
}

async function bundle(dir: string, items: readonly Entry[], tree: string): Promise<Output[]> {
  if (items.length === 0) return []
  const result = await Bun.build({
    entrypoints: items.map((item) => item.source),
    root: path.join(dir, "opencode", "src"),
    target: "bun",
    format: "esm",
    external: HOST_MODULES,
    splitting: false,
    minify: false,
    sourcemap: "none",
    plugins: [createSolidTransformPlugin()],
  })
  if (!result.success) throw new AggregateError(result.logs, `${path.relative(root, dir)}: build failed`)
  const outputs: Output[] = []
  for (const artifact of result.outputs) {
    if (artifact.kind !== "entry-point") continue
    // Keep Bun's `// @bun` pragma on the first line; Bun only honours it there.
    const text = await artifact.text()
    const contents = text.startsWith("// @bun\n") ? `// @bun\n${HEADER}${text.slice(8)}` : HEADER + text
    outputs.push({ file: path.join(dir, tree, "dist", artifact.path), contents })
  }
  return outputs
}

async function bundlePi(dir: string, items: readonly Entry[]): Promise<Output[]> {
  const outputs: Output[] = []
  for (const item of items) {
    const result = await Bun.build({
      entrypoints: [item.source],
      root: path.join(dir, "pi-src"),
      target: "bun",
      format: "esm",
      external: [...HOST_MODULES, ...PI_HOST_MODULES],
      splitting: false,
      minify: false,
      sourcemap: "none",
    })
    if (!result.success) throw new AggregateError(result.logs, `${path.relative(root, dir)}: pi build failed`)
    const artifact = result.outputs.find((output) => output.kind === "entry-point")
    if (artifact === undefined) throw new Error(`${path.relative(root, dir)}: pi build produced no entry point`)
    const text = await artifact.text()
    const contents = text.startsWith("// @bun\n") ? `// @bun\n${HEADER}${text.slice(8)}` : HEADER + text
    outputs.push({ file: path.join(dir, "pi", item.dist), contents })
  }
  return outputs
}

/** The bundles of the OpenCode, Claude Code and pi trees. */
export async function buildPlugin(dir: string, build = readBuild(dir)): Promise<Output[]> {
  if (build === undefined) return []
  const opencode = Object.entries(build.entries).map(([shim, name]): Entry => ({
    shim: `${shim}.js`,
    dist: `dist/${name}.js`,
    source: sourceOf(dir, name, shim),
  }))
  const claude = Object.entries(build.claudeEntries).map(([out, name]): Entry => ({
    dist: `dist/${out}.js`,
    source: sourceOf(dir, name, out),
  }))
  const pi = Object.entries(build.piEntries).map(([out, name]): Entry => ({
    dist: `extensions/${out}.js`,
    source: sourceOf(dir, name, out, "pi-src"),
  }))
  const outputs = [
    ...(await bundle(dir, opencode, "opencode")),
    ...(await bundle(dir, claude, "claude")),
    ...(await bundlePi(dir, pi)),
  ]
  for (const item of opencode) {
    outputs.push({
      file: path.join(dir, "opencode", item.shim as string),
      contents: `${HEADER}export { default } from "./${item.dist}"\nexport * from "./${item.dist}"\n`,
    })
  }
  return outputs
}

/** `common/.mcp.json` is copied to the root of every harness tree: Claude Code reads it, and the OpenCode plugin reads the same servers. */
export function mcpCopies(dir: string, harnesses: readonly string[]): Output[] {
  const source = path.join(dir, "common", ".mcp.json")
  if (!existsSync(source)) return []
  const contents = readFileSync(source, "utf8")
  return harnesses.map((harness) => ({ file: path.join(dir, harness, ".mcp.json"), contents }))
}

const AGENT_SOURCES = "agents.src"

/** The `common/agents/<id>.md` (`<id>.opencode.md` for a plugin with a Claude Code tree) composed from every `agents.src/<id>.md`. */
export function composeAgents(dir: string, claude = false, read?: (name: string) => string): Output[] {
  const sources = path.join(dir, AGENT_SOURCES)
  if (!existsSync(sources)) return []
  return readdirSync(sources)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => ({
      file: path.join(dir, "common", "agents", openCodeAgentFile(name.slice(0, -3), claude)),
      contents: composeAgentFile(readFileSync(path.join(sources, name), "utf8"), `${AGENT_SOURCES}/${name}`, read),
    }))
}

/** Composed agent files whose source is gone: they carry the generated comment but no build produces them. */
export function orphanAgents(dir: string, outputs: readonly Output[]): string[] {
  const agents = path.join(dir, "common", "agents")
  if (!existsSync(agents)) return []
  const expected = new Set(outputs.map((output) => output.file))
  return readdirSync(agents)
    .filter((name) => name.endsWith(".md") && !isTranslatedAgentFile(name))
    .map((name) => path.join(agents, name))
    .filter((file) => !expected.has(file))
    .filter((file) => readFileSync(file, "utf8").startsWith(`---\n${generatedComment(`${AGENT_SOURCES}/${path.basename(file).replace(/\.opencode\.md$/, ".md")}`)}\n`))
}

/** The OpenCode form of every agent of a plugin by id: composed, else hand-written in `common/agents/`. */
export function agentTexts(dir: string, claude: boolean, composed: readonly Output[]): Map<string, string> {
  const texts = new Map<string, string>()
  const agents = path.join(dir, "common", "agents")
  const suffix = claude ? ".opencode.md" : ".md"
  if (existsSync(agents)) {
    for (const name of readdirSync(agents)) {
      if (isTranslatedAgentFile(name) || !name.endsWith(suffix)) continue
      texts.set(name.slice(0, -suffix.length), readFileSync(path.join(agents, name), "utf8"))
    }
  }
  for (const output of composed) texts.set(path.basename(output.file).slice(0, -suffix.length), output.contents)
  return texts
}

/** The header every translated agent file starts with. */
const TRANSLATED_HEADER = "---\n# Generated by scripts/build.ts from "

/**
 * The OMP task agent (`common/agents/<id>.omp.md`) translated from every composed agent. harness-kit
 * copies it into the omp tree as `agents/<id>.md` when the plugin lists `omp`.
 */
export function ompAgents(dir: string, claude: boolean, composed: readonly Output[]): Output[] {
  const suffix = openCodeAgentFile("", claude)
  return composed.map((output) => {
    const name = path.basename(output.file)
    const id = name.slice(0, -suffix.length)
    const where = `plugins/${path.basename(dir)}/common/agents/${name}`
    return { file: path.join(dir, "common", "agents", ompAgentFile(id)), contents: translateOmpAgent(id, output.contents, where).contents }
  })
}

/** Translated OMP agents in `common/agents/` that a fresh build no longer produces; a hand-written `<id>.omp.md` is kept. */
export function staleOmpAgents(dir: string, outputs: readonly Output[]): string[] {
  const agents = path.join(dir, "common", "agents")
  if (!existsSync(agents)) return []
  const expected = new Set(outputs.map((output) => output.file))
  return readdirSync(agents)
    .filter((name) => name.endsWith(ompAgentFile("")))
    .map((name) => path.join(agents, name))
    .filter((file) => !expected.has(file) && readFileSync(file, "utf8").startsWith(TRANSLATED_HEADER))
}

function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath, entry.name))
}

const differs = (output: Output) => !existsSync(output.file) || readFileSync(output.file, "utf8") !== output.contents

/** Paths whose committed contents differ from a fresh build, or that the build no longer produces. */
export function stale(dir: string, outputs: readonly Output[]): string[] {
  const expected = new Set(outputs.map((output) => output.file))
  const extra = ["opencode", "claude"].flatMap((tree) => listFiles(path.join(dir, tree, "dist"))).filter((file) => !expected.has(file))
  const piExtra = listFiles(path.join(dir, "pi", "extensions"))
    .filter((file) => {
      if (expected.has(file)) return false
      const contents = readFileSync(file, "utf8")
      return contents.startsWith(HEADER) || contents.startsWith(`// @bun\n${HEADER}`)
    })
  return [...outputs.filter(differs).map((output) => output.file), ...extra, ...piExtra]
}

/** The plugin directories named in `only`, or all of them when it is empty; an unknown name throws. */
export function selectPlugins(dirs: readonly string[], only: readonly string[]): string[] {
  const unknown = only.filter((name) => !dirs.some((dir) => path.basename(dir) === name))
  if (unknown.length > 0) throw new Error(`unknown plugin: ${unknown.join(", ")}`)
  return only.length === 0 ? [...dirs] : dirs.filter((dir) => only.includes(path.basename(dir)))
}

async function main(check: boolean, only: readonly string[]) {
  // Bun names source files relative to the working directory in its output.
  process.chdir(root)
  const dirs = readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(pluginsDir, entry.name))
  const selected = selectPlugins(dirs, only)
  const problems: string[] = []
  const warnings: string[] = []
  for (const dir of selected) {
    const build = readBuild(dir)
    if (build === undefined) continue
    const composed = composeAgents(dir, build.claude)
    const orphans = orphanAgents(dir, composed)
    const omp = ompAgents(dir, build.claude, composed)
    const staleOmp = staleOmpAgents(dir, omp)
    const claude = build.claude
      ? claudeOutputs({ dir, agents: agentTexts(dir, true, composed), selected: build.claudeAgents }, (message) => warnings.push(message))
      : []
    const generated = [...composed, ...claude, ...omp, ...mcpCopies(dir, build.harnesses)]
    const bundles = await buildPlugin(dir, build)
    const staleBundles = stale(dir, bundles)
    const staleClaude = staleClaudeFiles({ dir }, claude)
    if (check) {
      problems.push(...generated.filter(differs).map((output) => output.file), ...orphans, ...staleClaude, ...staleOmp, ...staleBundles)
      continue
    }
    for (const file of [...orphans, ...staleClaude, ...staleOmp, ...staleBundles.filter((file) => !bundles.some((output) => output.file === file))]) rmSync(file)
    for (const tree of ["opencode", "claude"]) rmSync(path.join(dir, tree, "dist"), { recursive: true, force: true })
    for (const output of [...generated, ...bundles]) {
      mkdirSync(path.dirname(output.file), { recursive: true })
      writeFileSync(output.file, output.contents)
    }
    if (generated.length + bundles.length > 0) console.log(`built ${path.relative(root, dir)}`)
  }
  for (const warning of warnings) console.warn(`warning: ${warning}`)
  if (problems.length > 0) {
    console.error("Build output is stale. Run `bun run build` and commit the result:")
    for (const file of problems) console.error(`  ${path.relative(root, file)}`)
    process.exit(1)
  }
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  await main(args.includes("--check"), args.filter((arg) => !arg.startsWith("--")))
}
